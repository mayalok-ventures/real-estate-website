import fs from 'node:fs';
import path from 'node:path';
import esbuild from 'esbuild';

const rootDir = process.cwd();
const distClient = path.join(rootDir, 'dist', 'client');
const distServer = path.join(rootDir, 'dist', 'server');
const vercelStatic = path.join(rootDir, '.vercel', 'output', 'static');

console.log('[prepare-cloudflare] Synchronizing build output for Cloudflare Pages...');

// Clean and recreate target directory
if (fs.existsSync(vercelStatic)) {
  fs.rmSync(vercelStatic, { recursive: true, force: true });
}
fs.mkdirSync(vercelStatic, { recursive: true });

// Copy all static client assets into .vercel/output/static
if (fs.existsSync(distClient)) {
  fs.cpSync(distClient, vercelStatic, { recursive: true });
  console.log('[prepare-cloudflare] Copied dist/client -> .vercel/output/static');
}

// Bundle server entrypoint into a single self-contained _worker.js for Cloudflare Pages
if (fs.existsSync(distServer)) {
  const entryPath = path.join(distServer, 'entry.mjs');

  if (fs.existsSync(entryPath)) {
    const workerOutFile = path.join(vercelStatic, '_worker.js');
    console.log('[prepare-cloudflare] Bundling server entrypoint into _worker.js...');
    esbuild.buildSync({
      entryPoints: [entryPath],
      bundle: true,
      format: 'esm',
      platform: 'neutral',
      target: 'es2022',
      external: ['cloudflare:workers', 'node:*'],
      outfile: workerOutFile,
      logLevel: 'info',
    });
    console.log('[prepare-cloudflare] Successfully bundled _worker.js');
  }

  // Generate Cloudflare Pages _routes.json
  const routesConfig = {
    version: 1,
    include: [
      '/admin',
      '/admin/*',
      '/api/*',
      '/_server-islands/*',
      '/_image',
    ],
    exclude: [],
  };
  fs.writeFileSync(
    path.join(vercelStatic, '_routes.json'),
    JSON.stringify(routesConfig, null, 2)
  );
  console.log('[prepare-cloudflare] Generated _routes.json for Cloudflare Pages SSR routing');

  // Generate .assetsignore to ensure _worker.js and _routes.json are not treated as static assets
  fs.writeFileSync(
    path.join(vercelStatic, '.assetsignore'),
    '_worker.js\n_routes.json\n'
  );
}

// Copy public _headers if available
const publicHeaders = path.join(rootDir, 'public', '_headers');
if (fs.existsSync(publicHeaders)) {
  fs.copyFileSync(publicHeaders, path.join(vercelStatic, '_headers'));
}

// Clean up any redirect deploy config generated by Astro that conflicts with Pages
const deployConfigDir = path.join(rootDir, '.wrangler', 'deploy');
if (fs.existsSync(deployConfigDir)) {
  fs.rmSync(deployConfigDir, { recursive: true, force: true });
}

console.log('[prepare-cloudflare] Output directory .vercel/output/static is ready!');
